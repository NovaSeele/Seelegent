package snapshot

import (
	"bytes"
	"path"
	"strings"
)

// Why a file is at risk.
const (
	// WhyOutsideTools: a file that had uncommitted changes before the turn lost some of them (or was deleted), and
	// the worker's edit tools never touched it: a shell command or a script did.
	WhyOutsideTools = "outside_tools"
	// WhyLargeRemoval: the worker edited a file that had someone else's uncommitted changes and removed at least
	// LargeRemoval of those lines.
	WhyLargeRemoval = "large_removal"
)

// LargeRemoval is how many uncommitted lines an edited file must lose to be at risk.
const LargeRemoval = 5

// Risk is one file whose uncommitted work the turn may have lost.
type Risk struct {
	Path string
	Why  string
	// Lost counts the lines that were uncommitted before the turn and are gone after it.
	Lost    int
	Deleted bool
	Binary  bool
}

// Input is what Analyze compares.
type Input struct {
	Start, End Manifest
	// Edited holds the Key of every file the turn's edit tools changed.
	Edited map[string]bool
	// Others holds the Key of every file other tasks' tools changed during the turn.
	Others map[string]bool
	// Head returns the content of a file at the start commit (false when it has none).
	Head func(rel string) ([]byte, bool)
	// Content returns the stored content of a snapshot file.
	Content func(File) ([]byte, error)
}

// lockfiles are regenerated by tools; a change to one that still exists is not lost work.
var lockfiles = map[string]bool{"package-lock.json": true, "yarn.lock": true, "pnpm-lock.yaml": true,
	"cargo.lock": true, "poetry.lock": true, "uv.lock": true, "gemfile.lock": true, "composer.lock": true,
	"go.sum": true, "pipfile.lock": true, "npm-shrinkwrap.json": true}

// scratchDirs are tool scratch folders.
var scratchDirs = []string{".playwright-mcp/", ".codegraph/"}

// Scratch reports a path in a tool scratch folder.
func Scratch(rel string) bool {
	k := Key(rel)
	for _, d := range scratchDirs {
		if strings.HasPrefix(k, d) {
			return true
		}
	}
	return false
}

// Analyze returns the files whose uncommitted work the turn may have lost: files that were dirty when the turn
// started and whose content is different (or gone) when it ended, not changed by another task meanwhile, and
// that lost lines which were uncommitted at the start (see Why*). A truncated start snapshot only covers the files
// it holds.
func Analyze(in Input) []Risk {
	var out []Risk
	for _, before := range in.Start.Files {
		if before.Missing || before.Status == "" {
			continue // only work that existed and was uncommitted at the start can be lost
		}
		k := Key(before.Path)
		after, ok := in.End.Find(before.Path)
		if !ok {
			continue // not seen at the end: nothing to say
		}
		if after.Hash == before.Hash && after.Missing == before.Missing &&
			(before.Hash != "" || after.Size == before.Size) {
			continue // unchanged; a file too large to hash is compared by size
		}
		if in.Others[k] || Scratch(before.Path) || JunkName(before.Path) {
			continue
		}
		if lockfiles[strings.ToLower(path.Base(before.Path))] && !after.Missing {
			continue
		}
		edited := in.Edited[k]
		r := Risk{Path: before.Path, Deleted: after.Missing, Binary: before.Binary || after.Binary}
		switch {
		case r.Binary || !before.Stored:
			if edited {
				continue // an edit tool rewrote a binary or huge file on purpose
			}
			r.Why = WhyOutsideTools
		default:
			lost := lostLines(in, before, after)
			r.Lost = lost
			if edited {
				if lost < LargeRemoval {
					continue
				}
				r.Why = WhyLargeRemoval
			} else {
				if lost == 0 && !r.Deleted {
					continue
				}
				r.Why = WhyOutsideTools
			}
		}
		out = append(out, r)
	}
	return out
}

// lostLines counts the lines that were uncommitted at the start (in before, not at HEAD) and are not in after.
func lostLines(in Input, before, after File) int {
	b, err := in.Content(before)
	if err != nil {
		return 0
	}
	var a []byte
	if !after.Missing {
		if a, err = in.Content(after); err != nil {
			return 0
		}
	}
	var head []byte
	if in.Head != nil {
		head, _ = in.Head(before.Path)
	}
	uncommitted := subtract(lineCounts(b), lineCounts(head))
	removed := subtract(lineCounts(b), lineCounts(a))
	n := 0
	for line, c := range removed {
		n += min(c, uncommitted[line])
	}
	return n
}

// lineCounts is the multiset of the trimmed, non-empty lines of data.
func lineCounts(data []byte) map[string]int {
	m := map[string]int{}
	for _, l := range bytes.Split(data, []byte{'\n'}) {
		if t := strings.TrimSpace(string(l)); t != "" {
			m[t]++
		}
	}
	return m
}

func subtract(a, b map[string]int) map[string]int {
	out := map[string]int{}
	for k, v := range a {
		if d := v - b[k]; d > 0 {
			out[k] = d
		}
	}
	return out
}

// reserved are Windows device names a file must not be called.
var reserved = map[string]bool{"nul": true, "con": true, "prn": true, "aux": true}

// JunkName reports a file name that is leftover junk: a merge or patch leftover, a temporary or backup file, or a
// Windows device name (a stray `nul` from `> nul` in a POSIX shell).
func JunkName(rel string) bool {
	base := strings.ToLower(path.Base(strings.ReplaceAll(rel, `\`, "/")))
	for _, ext := range []string{".orig", ".rej", ".tmp", ".bak"} {
		if strings.HasSuffix(base, ext) {
			return true
		}
	}
	if strings.HasSuffix(base, "~") {
		return true
	}
	stem := base
	if i := strings.IndexByte(stem, '.'); i >= 0 {
		stem = stem[:i]
	}
	if reserved[stem] {
		return true
	}
	if len(stem) == 4 && (strings.HasPrefix(stem, "com") || strings.HasPrefix(stem, "lpt")) && stem[3] >= '1' &&
		stem[3] <= '9' {
		return true
	}
	return false
}
